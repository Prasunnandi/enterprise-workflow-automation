/**
 * BPMN 2.0 State Machine Parser & Token Execution Engine
 * Parses BPMN definitions, executes token navigation, and resolves exclusive (XOR) & parallel (AND) gateways.
 */

export class BpmnEngine {
  constructor() {
    this.instances = new Map(); // instanceId -> workflow state
  }

  /**
   * Parse a simplified BPMN JSON definition or process model
   * @param {Object} definition
   * @param {string} definition.id - Process ID
   * @param {Array<Object>} definition.nodes - Process nodes (startEvent, serviceTask, gateway, endEvent)
   * @param {Array<Object>} definition.flows - Sequence flows connecting nodes
   * @returns {Object} Validated executable process schema
   */
  loadProcess(definition) {
    if (!definition || !Array.isArray(definition.nodes) || !Array.isArray(definition.flows)) {
      throw new Error('Invalid BPMN definition: nodes and flows arrays are required');
    }

    const nodeMap = new Map(definition.nodes.map(n => [n.id, n]));
    const flowMap = new Map(definition.flows.map(f => [f.id, f]));

    // Find start event
    const startNode = definition.nodes.find(n => n.type === 'startEvent');
    if (!startNode) {
      throw new Error('BPMN process must contain at least one startEvent node');
    }

    return {
      processId: definition.id || 'process-1',
      startNodeId: startNode.id,
      nodes: nodeMap,
      flows: flowMap,
      raw: definition
    };
  }

  /**
   * Start a new workflow process instance
   * @param {Object} process - Output from loadProcess
   * @param {Object} [initialVariables={}] - Initial workflow payload
   * @returns {Object} Active process instance with token positions
   */
  startInstance(process, initialVariables = {}) {
    const instanceId = `inst-${Date.now()}-${Math.floor(Math.random() * 1000)}`;

    const instance = {
      instanceId,
      processId: process.processId,
      status: 'ACTIVE',
      variables: { ...initialVariables },
      tokens: [],
      history: [
        {
          timestamp: new Date().toISOString(),
          event: 'PROCESS_STARTED',
          nodeId: process.startNodeId
        }
      ]
    };

    this.instances.set(instanceId, instance);

    // Auto-advance from start event
    this._advanceToken(process, instance, process.startNodeId);

    return instance;
  }

  /**
   * Complete an active service or user task and progress token
   * @param {Object} process - Workflow definition
   * @param {string} instanceId - Running instance ID
   * @param {string} taskId - Node ID of task being completed
   * @param {Object} [outputVariables={}] - Data generated by task execution
   */
  completeTask(process, instanceId, taskId, outputVariables = {}) {
    const instance = this.instances.get(instanceId);
    if (!instance) throw new Error(`Instance not found: ${instanceId}`);
    if (instance.status !== 'ACTIVE') throw new Error(`Instance is not active (Status: ${instance.status})`);

    const tokenIdx = instance.tokens.indexOf(taskId);
    if (tokenIdx === -1) {
      throw new Error(`No active token waiting at task "${taskId}"`);
    }

    // Merge output variables
    Object.assign(instance.variables, outputVariables);

    instance.history.push({
      timestamp: new Date().toISOString(),
      event: 'TASK_COMPLETED',
      nodeId: taskId,
      outputs: outputVariables
    });

    // Remove current token and advance
    instance.tokens.splice(tokenIdx, 1);
    this._advanceToken(process, instance, taskId);

    return instance;
  }

  _advanceToken(process, instance, currentNodeId) {
    const currentNode = process.nodes.get(currentNodeId);
    if (!currentNode) return;

    // Check if end event
    if (currentNode.type === 'endEvent') {
      const idx = instance.tokens.indexOf(currentNodeId);
      if (idx !== -1) instance.tokens.splice(idx, 1);
      if (instance.tokens.length === 0) {
        instance.status = 'COMPLETED';
        instance.history.push({
          timestamp: new Date().toISOString(),
          event: 'PROCESS_COMPLETED',
          nodeId: currentNodeId
        });
      }
      return;
    }

    // Find outgoing sequence flows
    const outgoing = Array.from(process.flows.values()).filter(f => f.sourceRef === currentNodeId);

    if (outgoing.length === 0) return;

    if (currentNode.type === 'exclusiveGateway') {
      // XOR Gateway: follow first condition that evaluates to true, or default flow
      let chosenFlow = null;
      for (const flow of outgoing) {
        if (flow.condition) {
          if (this._evaluateCondition(flow.condition, instance.variables)) {
            chosenFlow = flow;
            break;
          }
        } else if (!chosenFlow) {
          chosenFlow = flow;
        }
      }

      if (chosenFlow) {
        const nextNode = process.nodes.get(chosenFlow.targetRef);
        instance.tokens.push(nextNode.id);
        instance.history.push({
          timestamp: new Date().toISOString(),
          event: 'GATEWAY_ROUTED',
          from: currentNodeId,
          to: nextNode.id,
          flowId: chosenFlow.id
        });

        // Continue recursion if next node is auto-executing
        if (nextNode.type === 'endEvent' || nextNode.type.includes('Gateway')) {
          const idx = instance.tokens.indexOf(nextNode.id);
          if (idx !== -1) instance.tokens.splice(idx, 1);
          this._advanceToken(process, instance, nextNode.id);
        }
      }
    } else {
      // Normal flow or StartEvent: advance to target node
      for (const flow of outgoing) {
        const nextNode = process.nodes.get(flow.targetRef);
        if (nextNode) {
          instance.tokens.push(nextNode.id);
          instance.history.push({
            timestamp: new Date().toISOString(),
            event: 'TOKEN_TRANSITION',
            from: currentNodeId,
            to: nextNode.id
          });

          if (nextNode.type === 'endEvent' || nextNode.type.includes('Gateway')) {
            const idx = instance.tokens.indexOf(nextNode.id);
            if (idx !== -1) instance.tokens.splice(idx, 1);
            this._advanceToken(process, instance, nextNode.id);
          }
        }
      }
    }
  }

  _evaluateCondition(conditionStr, variables) {
    try {
      // Safe key-value expression evaluator
      const keys = Object.keys(variables);
      const vals = Object.values(variables);
      const fn = new Function(...keys, `return Boolean(${conditionStr});`);
      return fn(...vals);
    } catch {
      return false;
    }
  }
}

export default BpmnEngine;
if (typeof module !== 'undefined' && module.exports) {
  module.exports = BpmnEngine;
  module.exports.BpmnEngine = BpmnEngine;
}
